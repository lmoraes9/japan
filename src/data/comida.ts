/**
 * Catálogo de comida da viagem — o mesmo conteúdo que já está espalhado pelas
 * paradas do roteiro, reorganizado por *tipo de comida* em vez de por dia.
 *
 * A ideia é bater o olho e saber o que tem: quantas refeições de sushi estão
 * na lista, quantas são omakase, quantas são de esteira, quantas são de rede.
 * Por isso cada item carrega `formato` — o rótulo que responde "que tipo de
 * lugar é esse?" — e não só uma descrição solta.
 *
 * `stopId` amarra cada item à parada de origem no roteiro: a data, a refeição
 * e o link saem de `ALL_DAYS`, então mexer no roteiro não deixa esta página
 * desatualizada. Os ids são conferidos em tempo de build por `comidaResolvida`.
 */

/** O rótulo que responde "que tipo de lugar é esse?" */
export type Formato =
  | 'omakase'
  | 'balcão'
  | 'kaiten'
  | 'rede'
  | 'izakaya'
  | 'bar'
  | 'beco'
  | 'de pé'
  | 'barraca'
  | 'mercado'
  | 'depachika'
  | 'kissaten'
  | 'templo'
  | 'casa antiga'
  | 'para viagem'
  | 'na estação'
  | 'com vista'
  | 'konbini';

/** Avisos práticos que mudam a hora de ir */
export type Aviso = 'fila' | 'reserva' | 'sem reserva' | 'esgota cedo' | 'só almoço' | '24h';

export type Preco = '¥' | '¥¥' | '¥¥¥' | '¥¥¥¥';

/** Como o item entra no roteiro */
export type Plano = 'marcado' | 'escolha' | 'plano B' | 'desvio';

export type ComidaCatId =
  | 'sushi'
  | 'ramen'
  | 'soba'
  | 'chapa'
  | 'katsu'
  | 'curry'
  | 'arroz'
  | 'templo'
  | 'mercado'
  | 'rua'
  | 'cafe'
  | 'bar'
  | 'konbini';

export interface ComidaCat {
  id: ComidaCatId;
  titulo: string;
  jp: string;
  /** uma linha: o que é essa categoria nesta viagem */
  resumo: string;
}

export interface ComidaItem {
  id: string;
  nome: string;
  jp?: string;
  cat: ComidaCatId;
  /** o que está no prato — é isso que separa uma tigela de ramen da outra */
  estilo?: string[];
  formato: Formato[];
  avisos?: Aviso[];
  preco?: Preco;
  /** especialidade típica daquela cidade/região */
  local?: boolean;
  plano: Plano;
  /** parada de origem no roteiro — data, refeição e link saem daí */
  stopId: string;
  /** sobrescreve o nome na busca de mapa/fotos quando o nome tem contexto */
  busca?: string;
  /** uma ou duas linhas, com a marcação de `Rich` */
  nota: string;
}

